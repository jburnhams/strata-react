import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

// The types behind `strata-api-types` (strata-react issue #263). A strata app's FastAPI server
// publishes its routes, the shared contracts (`strata_python.contracts`: Health, Task, Page, ErrorBody…)
// and its typed settings at `/api/openapi.json`; the TypeScript types follow that schema instead of
// being written again by hand and drifting. The work of reading OpenAPI is `openapi-typescript`
// (Jonathan, 2026-11-14: types only, nothing in the app's bundle); this file adds where the schema
// comes from (a running server, or a file the server's own CLI wrote, so CI needs no server) and what
// the committed file looks like. It lives behind its own entry (`strata-react/api-types`), like
// `strata-react/visual`, and `openapi-typescript` is an optional peer, so an app that never runs the
// command installs nothing and the main entry's peer contract is unchanged.
//
// The output is deterministic, so `--check` can compare it with the committed file and fail CI when
// the Python side moved and the file did not. Nothing about the machine (the URL it was read from, a
// date) goes into it, for the same reason.

/** The OpenAPI document as the generator takes it: a parsed JSON object. */
export type OpenApiDocument = Record<string, unknown>;

/** Reads an OpenAPI document from an `http(s)` URL (a running server) or a JSON file path. */
export async function loadSchema(source: string, fetcher: typeof fetch = fetch): Promise<OpenApiDocument> {
  let text: string;
  if (/^https?:\/\//i.test(source)) {
    const response = await fetcher(source, { headers: { accept: "application/json" } });
    if (!response.ok) throw new Error(`${source} answered ${response.status} ${response.statusText}`);
    text = await response.text();
  } else {
    text = await readFile(source, "utf8");
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    throw new Error(`${source} is not JSON. Give the OpenAPI document (/api/openapi.json), not the docs page.`);
  }
  if (!parsed || typeof parsed !== "object" || !("openapi" in parsed)) throw new Error(`${source} is JSON but not an OpenAPI document (no "openapi" field).`);
  return parsed as OpenApiDocument;
}

const header = `/* eslint-disable */
// Generated by strata-api-types from the app's OpenAPI schema. Do not edit by hand:
// regenerate with \`strata-api-types <schema> -o <this file>\`; CI runs it with --check.
`;

// Short names for the schemas, so a screen writes \`Schema<"Task">\` and not the whole path.
const footer = `
/** A named schema of the API: \`Schema<"Task">\`. */
export type Schema<K extends keyof components["schemas"]> = components["schemas"][K];
`;

/** The URL relative references resolve against: the document's own URL, or its file's location. */
function baseOf(source: string): URL {
  return /^https?:\/\//i.test(source) ? new URL(source) : pathToFileURL(resolve(source));
}

/**
 * The TypeScript types for an OpenAPI document, as the text of the generated file. `source` is where the
 * document was read from (a URL or file path): relative `$ref`s to other files resolve against it.
 */
export async function generateApiTypes(schema: OpenApiDocument, source?: string): Promise<string> {
  const mod = await import("openapi-typescript").catch(() => {
    throw new Error("strata-api-types needs openapi-typescript: npm install --save-dev openapi-typescript (it also wants TypeScript 5 or an override that points it at yours).");
  });
  const { default: openapiTS, astToString } = mod;
  const ast = await openapiTS(schema as never, source ? { cwd: baseOf(source) } : undefined);
  return `${header}\n${astToString(ast).trimEnd()}\n${footer}`;
}
