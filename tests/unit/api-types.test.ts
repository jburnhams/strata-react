import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { main } from "../../src/api-types/cli";
import { generateApiTypes, loadSchema } from "../../src/api-types/generate";

// Issue #263: the types follow the server's OpenAPI schema (a FastAPI-shaped fixture), and --check
// is how CI notices the Python side moved.

const fixture = join(__dirname, "../fixtures/openapi.json");

describe("generateApiTypes", () => {
  it("writes the contract shapes as TypeScript, deterministically, with nothing of the machine in it", async () => {
    const text = await generateApiTypes(await loadSchema(fixture));
    expect(text).toContain("Generated by strata-api-types");
    expect(text).toMatch(/Task: \{[^}]*state: components\["schemas"\]\["TaskState"\]/s);
    expect(text).toContain('TaskState: "queued" | "running" | "done" | "failed" | "cancelled"');
    expect(text).toMatch(/next: string \| null/);
    expect(text).toMatch(/payload\?: \{\s*\[key: string\]: unknown;\s*\} \| null/);
    expect(text).toContain('export type Schema<K extends keyof components["schemas"]>');
    expect(text).not.toMatch(/localhost|\/home\//);
    expect(await generateApiTypes(await loadSchema(fixture))).toBe(text);
  });
});

describe("loadSchema", () => {
  it("reads a URL and says what is wrong with a docs page or a non-OpenAPI file", async () => {
    const answer = (body: string, init?: ResponseInit) => (async () => new Response(body, init)) as unknown as typeof fetch;
    const doc = readFileSync(fixture, "utf8");
    expect((await loadSchema("http://localhost:8360/api/openapi.json", answer(doc))).openapi).toBe("3.1.0");
    await expect(loadSchema("http://x/docs", answer("<html></html>"))).rejects.toThrow(/not JSON/);
    await expect(loadSchema("http://x/a", answer("{}"))).rejects.toThrow(/not an OpenAPI document/);
    await expect(loadSchema("http://x/a", answer("no", { status: 404, statusText: "Not Found" }))).rejects.toThrow(/404 Not Found/);
  });
});

describe("strata-api-types", () => {
  const run = async (...args: string[]) => {
    const lines: string[] = [];
    const code = await main(args, (t) => lines.push(t));
    return { code, text: lines.join("\n") };
  };

  it("writes the file, then --check passes until the schema moves, and says how to fix it", async () => {
    const dir = mkdtempSync(join(tmpdir(), "strata-api-"));
    const out = join(dir, "api.generated.ts");
    expect((await run(fixture, "-o", out, "--check")).code).toBe(1); // missing
    expect((await run(fixture, "-o", out)).code).toBe(0);
    expect(readFileSync(out, "utf8")).toContain("export interface components");
    expect(await run(fixture, "-o", out, "--check")).toMatchObject({ code: 0 });
    const moved = JSON.parse(readFileSync(fixture, "utf8"));
    moved.components.schemas.Health.properties.uptime = { type: "number", title: "Uptime" };
    const changed = join(dir, "moved.json");
    writeFileSync(changed, JSON.stringify(moved));
    const stale = await run(changed, "-o", out, "--check");
    expect(stale.code).toBe(1);
    expect(stale.text).toMatch(/no longer matches the schema\. Regenerate it: strata-api-types .* -o /);
    expect(readFileSync(out, "utf8")).not.toContain("uptime"); // --check writes nothing
  });

  it("explains a missing schema argument and an unknown option", async () => {
    expect((await run()).code).toBe(2);
    expect((await run("--nope")).code).toBe(2);
    expect((await run("--help")).code).toBe(0);
    expect((await run("/no/such/file.json")).code).toBe(1);
  });
});
